#!/usr/bin/env python3
"""Publish local build output, or generate a style adapter for the old preview."""
import argparse
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT.parent / 'cmssdt-web/html/cmssdt-ib-react19'

def legacy_css():
    css = (ROOT / 'src/dashboard.css').read_text()
    aliases = {
        '.ib-release-panel-header': '#root .card > .card-header[role="button"]',
        '.ib-release-panel-body': '#root .card:has(> .card-header[role="button"]) > .card-body',
        '.ib-release-panel {': '#root .card.mb-3:has(> .card-header[role="button"]) {',
    }
    # Old bundles still ship global resets and inline styles. The adapter is
    # generated only for that transitional preview; React source doesn't use it.
    for original, replacement in aliases.items():
        css = css.replace(original, replacement)
    css = re.sub(r'([\w-]+\s*:[^;{}]+);', lambda m: m[1].replace(' !important', '') + ' !important;', css)
    # The old reset also fixes card width: derive this from the same inset token.
    css += '\n#root .card.mb-3:has(> .card-header[role="button"]) { width: calc(100% - 2 * var(--ui-page-inset)) !important; }\n'
    return '/* Generated by scripts/sync-preview.py; do not edit. */\n' + (ROOT / 'src/styles/tokens.css').read_text() + css

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build', action='store_true', help='Copy a completed Vite build, including React changes')
    args = parser.parse_args()
    if args.build:
        dist = ROOT / 'dist'
        if not (dist / 'index.html').is_file():
            parser.error('Run npm run build first')
        for item in dist.iterdir():
            if item.name in {'SDT', 'updateData.sh'}:
                continue  # Never copy downloaded datasets or maintenance scripts.
            dest = TARGET / item.name
            if item.is_dir():
                shutil.copytree(item, dest, dirs_exist_ok=True)
            else:
                shutil.copy2(item, dest)
        print('Published local React build to', TARGET)
    else:
        index = TARGET / 'index.html'
        html = index.read_text()
        # Refuse to add legacy rules after a modern build has been published.
        if 'href="./dashboard.css"' not in html:
            parser.error('Preview is not the legacy bundle; use npm run build:preview')
        (TARGET / 'dashboard.css').write_text(legacy_css())
        print('Generated legacy preview stylesheet; React changes require npm run build:preview')

if __name__ == '__main__':
    main()
